type QuizSeed = {
  question: string;
  options: string[];
  correctAnswer: string;
  explanation: string;
};

type LessonSeed = {
  title: string;
  estimatedMinutes: number;
  theory: string[];
  quizzes: QuizSeed[];
};

type CourseSeed = {
  title: string;
  description: string;
  difficulty: string;
  imageGradient: string;
  lessons: LessonSeed[];
};

type LessonBlueprint = {
  title: string;
  estimatedMinutes: number;
  concept: string;
  importance: string;
  firstStep: string;
  commonMistake: string;
  practicalAction: string;
  expectedResult: string;
  example: string;
};

function buildTheory(lesson: LessonBlueprint) {
  return [
    `${lesson.concept}. В этом уроке студент разбирает тему не только на уровне определения, но и на уровне реального применения в учебной аналитике и проектах по искусственному интеллекту.`,
    `Почему это важно. ${lesson.importance}. Если этот шаг пропустить, дальше появляются ошибки в выводах, графиках и интерпретации результатов.`,
    `С чего начать. ${lesson.firstStep}. Такой порядок помогает не теряться в данных и сразу выстраивать понятную последовательность действий.`,
    `Типичная ошибка новичка. ${lesson.commonMistake}. Именно поэтому на платформе мы учим не просто нажимать кнопки, а понимать смысл каждого действия.`,
    `Практика. ${lesson.practicalAction}. После этого студент может перейти к визуализации, расчётам или построению модели уже на более надёжной основе.`,
    `Пример из образовательного кейса. ${lesson.example}. Ожидаемый результат урока: ${lesson.expectedResult}.`,
  ];
}

function buildQuizzes(lesson: LessonBlueprint) {
  return [
    {
      question: `Какова главная цель темы «${lesson.title}»?`,
      options: [lesson.expectedResult, "Случайно изменить интерфейс платформы", "Пропустить этап анализа и сразу отправить ответ"],
      correctAnswer: lesson.expectedResult,
      explanation: `Смысл темы в том, чтобы студент освоил практический результат: ${lesson.expectedResult.toLowerCase()}.`,
    },
    {
      question: `Какой первый шаг наиболее уместен в теме «${lesson.title}»?`,
      options: [lesson.firstStep, "Сразу строить любую модель без подготовки", "Игнорировать структуру данных и описание задачи"],
      correctAnswer: lesson.firstStep,
      explanation: `Первый шаг задаёт качество всей дальнейшей работы, поэтому здесь важно именно: ${lesson.firstStep.toLowerCase()}.`,
    },
    {
      question: `Какой вариант описывает типичную ошибку по теме «${lesson.title}»?`,
      options: [lesson.commonMistake, "Проверка результата и объяснение вывода", "Аккуратная работа с данными по шагам"],
      correctAnswer: lesson.commonMistake,
      explanation: "Эта ошибка встречается часто и приводит к тому, что студент делает неубедительный или неверный вывод.",
    },
    {
      question: `Какое практическое действие лучше всего закрепляет тему «${lesson.title}»?`,
      options: [lesson.practicalAction, "Оставить задачу без примера и без комментариев", "Скопировать случайный ответ из интернета"],
      correctAnswer: lesson.practicalAction,
      explanation: "Платформа AI DataLab делает упор на практику, поэтому закрепление темы всегда связано с реальным действием.",
    },
    {
      question: `Какой итог показывает, что урок «${lesson.title}» действительно усвоен?`,
      options: [lesson.expectedResult, "Студент только открыл страницу и сразу закрыл её", "Студент запомнил название темы, но не понял смысла"],
      correctAnswer: lesson.expectedResult,
      explanation: "Усвоение темы видно по практическому результату, а не по формальному присутствию на уроке.",
    },
  ];
}

function createLesson(blueprint: LessonBlueprint): LessonSeed {
  return {
    title: blueprint.title,
    estimatedMinutes: blueprint.estimatedMinutes,
    theory: buildTheory(blueprint),
    quizzes: buildQuizzes(blueprint),
  };
}

