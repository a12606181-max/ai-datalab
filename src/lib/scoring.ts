const KEYWORDS = ["график", "вывод", "данные", "модель", "точность", "признаки"];

export function scoreLabSubmission(answerText: string) {
  let score = 20;
  const lowered = answerText.toLowerCase();
  const matchedKeywords = KEYWORDS.filter((keyword) => lowered.includes(keyword));

  if (answerText.length > 100) score += 20;
  score += matchedKeywords.length * 10;

  if (lowered.includes("анализ")) score += 10;
  if (lowered.includes("рекомен")) score += 10;

  const finalScore = Math.min(100, score);

  const strengths = [
    matchedKeywords.length >= 2
      ? "Ответ использует профильную лексику аналитики данных."
      : "Ответ отражает понимание учебного кейса.",
    answerText.length > 100
      ? "Студент дал развёрнутое объяснение и не ограничился коротким выводом."
      : "Есть базовая структура решения.",
  ];

  const improvements = [
    matchedKeywords.includes("график")
      ? "Добавьте численные результаты и интерпретацию метрик для усиления аргументации."
      : "Уточните, какие визуализации и метрики вы использовали при анализе.",
    lowered.includes("модель")
      ? "Поясните, почему выбранная модель подходит именно для этого кейса."
      : "Опишите, какие признаки и шаги предобработки могут улучшить результат.",
  ];

  const mentorTip =
    finalScore >= 80
      ? "ИИ-наставник рекомендует перейти к следующей лабораторной и сравнить несколько подходов к анализу."
      : "ИИ-наставник рекомендует дополнить решение графиками, признаками и более чётким выводом.";

  return {
    score: finalScore,
    feedback: [
      "Сильные стороны:",
      ...strengths.map((item) => `- ${item}`),
      "",
      "Что улучшить:",
      ...improvements.map((item) => `- ${item}`),
      "",
      `Рекомендация ИИ-наставника: ${mentorTip}`,
    ].join("\n"),
  };
}

export function generateMentorReply(message: string) {
  const normalized = message.toLowerCase();

  if (normalized.includes("регресс")) {
    return "Регрессия помогает предсказывать числовое значение. Начните с выбора целевой переменной, проверьте признаки и сравните качество модели по метрикам MAE или RMSE.";
  }

  if (normalized.includes("очист") || normalized.includes("пропуск")) {
    return "При очистке данных сначала найдите пропуски, дубликаты и выбросы. Затем зафиксируйте стратегию: удалить, заполнить средним значением или использовать доменное правило.";
  }

  if (normalized.includes("модель") || normalized.includes("точност")) {
    return "Если модель ошибается, проверьте качество признаков, баланс классов, размер обучающей выборки и метрики. Часто полезно сравнить несколько моделей и сделать кросс-валидацию.";
  }

  if (normalized.includes("график")) {
    return "Для сравнения категорий подойдёт столбчатая диаграмма, для динамики по времени лучше выбрать линейный график. Сначала определите, что именно вы хотите показать зрителю.";
  }

  if (normalized.includes("признак")) {
    return "Признаки — это характеристики объектов, по которым модель ищет закономерности. Полезно проверить, какие из них действительно влияют на целевую переменную.";
  }

  return "Продолжайте мыслить как аналитик: сформулируйте задачу, проверьте качество данных, выберите подходящий метод анализа и только потом переходите к выводам. Если хотите, я помогу разобрать это по шагам.";
}
